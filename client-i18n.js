export function getClientLanguage() {
    return localStorage.getItem('phonehaven_client_lang') || 'fr';
}

export function setClientLanguage(lang) {
    if (lang !== 'fr' && lang !== 'ar') lang = 'fr';
    localStorage.setItem('phonehaven_client_lang', lang);
    applyClientLanguage(lang);
}

export function tClient(key, lang = null) {
    const activeLang = lang || getClientLanguage();
    const dict = clientTranslations[activeLang] || clientTranslations.fr;
    return dict[key] || clientTranslations.fr[key] || key;
}

export function formatPriceClient(price, lang = null) {
    const activeLang = lang || getClientLanguage();
    const formatted = new Intl.NumberFormat(activeLang === 'ar' ? 'ar-DZ' : 'fr-DZ').format(price || 0);
    return `${formatted} ${tClient('price_da', activeLang)}`;
}

export function getStatusLabelClient(status, lang = null) {
    const activeLang = lang || getClientLanguage();
    return tClient(`status_${status}`, activeLang) || status;
}

export function applyClientLanguage(lang = null) {
    const activeLang = lang || getClientLanguage();
    const isAr = activeLang === 'ar';

    // Document HTML tag
    document.documentElement.lang = activeLang;
    document.documentElement.dir = isAr ? 'rtl' : 'ltr';

    if (isAr) {
        document.body.classList.add('font-arabic');
    } else {
        document.body.classList.remove('font-arabic');
    }

    // Translate all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (key) {
            const translated = tClient(key, activeLang);
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = translated;
            } else {
                el.textContent = translated;
            }
        }
    });

    // Update Language Toggle Button in Navbar (desktop & mobile)
    const toggleBtns = document.querySelectorAll('.client-lang-toggle');
    toggleBtns.forEach(btn => {
        btn.innerHTML = `
            <span class="text-sm">${isAr ? '🇫🇷' : '🇩🇿'}</span>
            <span class="text-xs font-bold">${isAr ? 'Français' : 'العربية'}</span>
        `;
    });

    // Dispatch custom event for dynamic components (like algeria-coverage map)
    window.dispatchEvent(new CustomEvent('clientLanguageChanged', { detail: { lang: activeLang } }));
}

export function initClientLanguage() {
    const currentLang = getClientLanguage();
    applyClientLanguage(currentLang);

    // Attach click listeners to all toggle buttons (desktop + mobile)
    document.querySelectorAll('.client-lang-toggle').forEach(btn => {
        btn.onclick = (e) => {
            e.preventDefault();
            const newLang = getClientLanguage() === 'fr' ? 'ar' : 'fr';
            setClientLanguage(newLang);
        };
    });
}

// Auto-run when DOM ready
if (typeof window !== 'undefined') {
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initClientLanguage);
    } else {
        initClientLanguage();
    }
}
